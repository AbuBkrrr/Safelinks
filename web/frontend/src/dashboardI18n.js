export function dt(lang, key, vars) {
  const strings = STRINGS[lang] || STRINGS.en;
  let s = strings[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
  }
  return s;
}

// Voice-command "match" strings are stored semicolon-separated (see the
// voiceMatch* keys above) since a single phrase isn't always how a
// command reads naturally in every language. Splits + trims for use in
// a VoiceAssistant `commands` match array.
export function dtMatch(lang, key) {
  return dt(lang, key).split(";").map((s) => s.trim()).filter(Boolean);
}
