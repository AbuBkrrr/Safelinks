export function t(lang, key, vars) {
  const strings = STRINGS[lang] || STRINGS.en;
  let s = strings[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, vars[k]);
  }
  return s;
}
